--[[
	Engine/SkinSlice.lua
	Pure maths for drawing set-skin art without stretching it. Uses the measured art boxes in SetSkinMetrics.lua
	(generated by tools/patron_art/measure_skin_art.py): the image is cropped to its visible art with
	ImageRectOffset/ImageRectSize, then 9-sliced so the caps keep their proportions at any size.
	Used by Client/SetSkin.lua.
]]

local Metrics = require(script.Parent.SetSkinMetrics)

local SkinSlice = {}

SkinSlice.CAP_FRACTION = 0.17 -- button / tab caps: share of the cropped width on each side
SkinSlice.RAIL_FRACTION = 0.25 -- top and bottom rail: share of the cropped height
SkinSlice.PANEL_EDGE_FRACTION = 0.125 -- panel frame border: share of the short side of the crop
SkinSlice.WIDE_PX = 160 -- plates wider than this show only the plain middle rails (no lantern end, no smudged end)
SkinSlice.WIDE_FROM = 0.26 -- plain-rail crop of a wide plate: share of the cropped width where it starts
SkinSlice.WIDE_TO = 0.80 -- and where it ends
SkinSlice.WIDE_CAP = 6 -- source px kept as an end cap on a wide plate (the button is rounded with a corner instead)
SkinSlice.MIN_CAPS_WIDE = 3 -- narrower than this many caps and the plate falls back to flat colour
SkinSlice.MAX_FRAME_SHRINK = 0.08 -- per side, used when a frame's inner window is too small for the index
SkinSlice.INDEX_PAD = 0.02 -- card fraction between the window edge and the index

function SkinSlice.metrics(setId, slot)
	local set = setId and Metrics[setId]
	return set and set[slot] or nil
end

-- Crop rectangle of the visible art: offset x,y and size w,h in source px.
function SkinSlice.crop(m)
	if not m then return nil end
	return { x = m.x, y = m.y, w = m.cw, h = m.ch }
end

-- 9-slice for a button or tab plate drawn at btnW x btnH. Returns nil when the plate is too small for its caps (use a
-- flat coloured plate). Otherwise { center = {l,t,r,b} in crop px, scale, capW } where capW is the on-screen cap width.
-- SliceScale makes the whole art height equal the button height, so caps are never scaled non-uniformly.
function SkinSlice.plateSlice(m, btnW, btnH)
	if not m or btnW <= 0 or btnH <= 0 then return nil end
	local scale = btnH / m.ch
	if btnW > SkinSlice.WIDE_PX then
		local x0 = math.floor(m.cw * SkinSlice.WIDE_FROM)
		local x1 = math.floor(m.cw * SkinSlice.WIDE_TO)
		local w = x1 - x0
		local rail = math.floor(m.ch * SkinSlice.RAIL_FRACTION)
		return {
			center = { l = SkinSlice.WIDE_CAP, t = rail, r = w - SkinSlice.WIDE_CAP, b = m.ch - rail },
			scale = scale,
			capW = SkinSlice.WIDE_CAP * scale,
			crop = { x = m.x + x0, y = m.y, w = w, h = m.ch },
			wide = true,
		}
	end
	local capSrc = math.floor(m.cw * SkinSlice.CAP_FRACTION)
	local capW = capSrc * scale
	if btnW < capW * SkinSlice.MIN_CAPS_WIDE then return nil end
	local rail = math.floor(m.ch * SkinSlice.RAIL_FRACTION)
	return {
		center = { l = capSrc, t = rail, r = m.cw - capSrc, b = m.ch - rail },
		scale = scale,
		capW = capW,
	}
end

-- 9-slice for a panel frame whose visible border should draw `band` px thick.
function SkinSlice.panelSlice(m, band)
	if not m or band <= 0 then return nil end
	local edge = math.floor(math.min(m.cw, m.ch) * SkinSlice.PANEL_EDGE_FRACTION)
	return { center = { l = edge, t = edge, r = m.cw - edge, b = m.ch - edge }, scale = band / edge, edge = edge }
end

-- Where the corner index may sit on a card whose frame art is drawn at `shrink` per side. Returns fractions of the card:
-- { x, y, w, h, shrink }. The inner window is measured in the frame crop; a window that is too small for the index
-- shrinks the frame (up to MAX_FRAME_SHRINK per side) instead of covering it.
function SkinSlice.indexWindow(m)
	local fallback = { x = 0.14, y = 0.1, w = 0.72, h = 0.8 }
	if not m or not m.iw then
		return { x = fallback.x, y = fallback.y, w = fallback.w, h = fallback.h, shrink = 0 }
	end
	local u = { x = (m.ix - m.x) / m.cw, y = (m.iy - m.y) / m.ch, w = m.iw / m.cw, h = m.ih / m.ch }
	local shrink = 0
	if u.x < 0.1 or u.y < 0.07 or u.w < 0.5 or u.h < 0.55 then
		shrink = SkinSlice.MAX_FRAME_SHRINK
		-- a window that cannot fit even then falls back to a fixed inner box
		if u.w < 0.4 or u.h < 0.45 then u = { x = 0.12, y = 0.08, w = 0.76, h = 0.84 } end
	end
	local span = 1 - 2 * shrink
	return { x = shrink + u.x * span, y = shrink + u.y * span, w = u.w * span, h = u.h * span, shrink = shrink }
end

-- Positions (card fractions) for the corner rank, corner suit and bottom-right suit inside a window.
function SkinSlice.indexLayout(win)
	local pad = SkinSlice.INDEX_PAD
	local x, y = win.x + pad, win.y + pad
	return {
		rank = { x = x, y = y, w = 0.26, h = 0.15 },
		suit = { x = x, y = y + 0.15, w = 0.18, h = 0.1 },
		bottom = { x = win.x + win.w - pad, y = win.y + win.h - pad, w = 0.16, h = 0.1 },
	}
end

return SkinSlice
