--[[
	Shared/Engine/ContentArt.lua
	Central lookup table that maps (tab, id) -> rbxassetid for every category of
	art in the game. Backed by per-category files generated by
	tools/patron_art/generate_patron_art.py -- do not hand-edit those files.

	Usage:
	  local artId = ContentArt.getImageId("patrons", patronId)   -- nil when no art
	  local artId = ContentArt.getImageId("boss_rounds", bossId)
	  -- etc.

	Tab names match CollectionBook tab ids: patrons, recipes, boss_rounds,
	house_passes, titles.
]]

local Engine = script.Parent

local ContentArt = {
	patrons      = require(Engine:WaitForChild("PatronArt")),
	boss_rounds  = require(Engine:WaitForChild("BossRoundArt")),
	recipes      = require(Engine:WaitForChild("RecipeArt")),
	house_passes = require(Engine:WaitForChild("HousePassArt")),
	titles       = require(Engine:WaitForChild("TitleArt")),
	rooms        = require(Engine:WaitForChild("RoomArt")),
	backgrounds  = require(Engine:WaitForChild("BackgroundArt")),
}
-- CollectionBook tab ids use different names; alias them so both work.
ContentArt.bosses      = ContentArt.boss_rounds
ContentArt.housePasses = ContentArt.house_passes

function ContentArt.getImageId(tab, id)
	local t = ContentArt[tab]
	if not t then return nil end
	local v = t[id]
	if type(v) ~= "string" or v == "" or v == "rbxassetid://0" then return nil end
	return v
end

return ContentArt
