--[[
	Shared/Engine/ContentArt.lua
	Central lookup table that maps (tab, id) -> rbxassetid for every category of
	art in the game. Backed by per-category files generated by
	tools/patron_art/generate_patron_art.py -- do not hand-edit those files.

	Usage:
	  local artId = ContentArt.getImageId("patrons", patronId)   -- nil when no art
	  local artId = ContentArt.getImageId("boss_rounds", bossId)
	  -- etc.

	Tab names match CollectionBook tab ids: patrons, recipes, boss_rounds,
	house_passes, titles, rooms, backgrounds, tutorial_icons.
]]

local Engine = script.Parent

local ContentArt = {
	patrons      = require(Engine:WaitForChild("PatronArt")),
	boss_rounds  = require(Engine:WaitForChild("BossRoundArt")),
	recipes      = require(Engine:WaitForChild("RecipeArt")),
	house_passes = require(Engine:WaitForChild("HousePassArt")),
	titles       = require(Engine:WaitForChild("TitleArt")),
	rooms        = require(Engine:WaitForChild("RoomArt")),
	backgrounds  = require(Engine:WaitForChild("BackgroundArt")),
	tutorial_icons = require(Engine:WaitForChild("TutorialIconArt")),
	map_nodes    = require(Engine:WaitForChild("MapNodeArt")),
	hud          = require(Engine:WaitForChild("HudArt")),
	menu_icons   = require(Engine:WaitForChild("MenuIconArt")),
	map_regions  = require(Engine:WaitForChild("MapRegionArt")),
	map_decor    = require(Engine:WaitForChild("MapDecorArt")),
	card_backs   = require(Engine:WaitForChild("CardBackArt")),
	fx           = require(Engine:WaitForChild("FxArt")),
	scenes       = require(Engine:WaitForChild("SceneArt")),
	packs        = require(Engine:WaitForChild("PackArt")),
}
-- CollectionBook tab ids use different names; alias them so both work.
ContentArt.bosses      = ContentArt.boss_rounds
ContentArt.housePasses = ContentArt.house_passes

function ContentArt.getImageId(tab, id)
	local t = ContentArt[tab]
	if not t then return nil end
	local v = t[id]
	if type(v) ~= "string" or v == "" or v == "rbxassetid://0" then return nil end
	return v
end

-- Warm the asset cache so tiles built later find their art already loaded
-- (no emoji/placeholder flash). Non-blocking by design: callers run it inside
-- task.spawn. Runs once per session; later calls return immediately.
-- Roblox-only (ContentProvider); a no-op under the plain-Lua test runner.
local preloadStarted = false
function ContentArt.preloadAll()
	if preloadStarted then return end
	local okSvc, ContentProvider = pcall(function() return game:GetService("ContentProvider") end)
	if not okSvc or not ContentProvider then return end
	preloadStarted = true
	local seen, urls = {}, {}
	for key, map in pairs(ContentArt) do
		if type(map) == "table" and key ~= "bosses" and key ~= "housePasses" then
			for _, v in pairs(map) do
				if type(v) == "string" and v ~= "" and v ~= "rbxassetid://0" and not seen[v] then
					seen[v] = true
					table.insert(urls, v)
				end
			end
		end
	end
	local BATCH = 25
	for i = 1, #urls, BATCH do
		local batch = {}
		for j = i, math.min(i + BATCH - 1, #urls) do table.insert(batch, urls[j]) end
		pcall(function() ContentProvider:PreloadAsync(batch) end)
		task.wait()
	end
end

return ContentArt
