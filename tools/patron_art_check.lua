-- Writes claude/PATRON_ART_CHECK.md from code only: every Patron with its art keys and ids and whether the portrait resolves at each size.
-- Run from the project root: lua tools/patron_art_check.lua
local src = "src/Shared"
local cache = {}
local function proxy(path)
	return setmetatable({ __path = path }, {
		__index = function(_, key)
			if key == "WaitForChild" then return function(self, n) return self[n] end end
			if key == "Parent" then return proxy(path:match("(.*)/[^/]+$") or ".") end
			return proxy(path .. "/" .. key)
		end,
	})
end
local function load(path)
	if cache[path] then return cache[path] end
	local env = setmetatable({ script = proxy(path) }, { __index = _G })
	env.require = function(t) return load(t.__path) end
	local chunk = assert(loadfile(path .. ".lua", "t", env))
	cache[path] = chunk()
	return cache[path]
end
Color3 = Color3 or { fromRGB = function(r, g, b) return { r = r, g = g, b = b } end }
local Patrons = load(src .. "/Engine/Patrons")
local Plain = load(src .. "/Engine/PatronArt")
local Cards = load(src .. "/Engine/ConceptTPatronArt")
local Crops = load(src .. "/Engine/PatronCardCrop")

local function usable(v) return type(v) == "string" and v ~= "" and v ~= "rbxassetid://0" end
local function digits(v) return usable(v) and v:match("%d+") or "-" end

local rows, issues = {}, {}
local rankOf = { common = 1, uncommon = 2, rare = 3, epic = 4, legendary = 5 }
local defs = {}
for _, p in ipairs(Patrons.Definitions) do defs[#defs + 1] = p end
table.sort(defs, function(a, b)
	local ra, rb = rankOf[a.rarity or "common"] or 9, rankOf[b.rarity or "common"] or 9
	if ra ~= rb then return ra < rb end
	return a.id < b.id
end)
local ok = 0
local noPlain = {}
for _, p in ipairs(defs) do
	local card, plain, crop = Cards["ctp_" .. p.id], Plain[p.id], Crops[p.id]
	-- Counter and My Patrons (PatronPlaque): the cut card wins, then the plain portrait, then the emoji
	local plaque = usable(card) and "card" or (usable(plain) and "plain" or "EMOJI")
	-- the pick ring (DraftPortrait.spec): cut card with a crop, else the plain portrait fitted, else the emoji
	local ring = (usable(card) and crop) and "card crop" or (usable(plain) and "plain fit" or "EMOJI")
	-- the seat circle uses the same picture as the plaque
	local seat = plaque
	local status = "ok"
	if plaque == "EMOJI" or ring == "EMOJI" then status = "MISSING"
	elseif plaque == "plain" or ring == "plain fit" then status = "no cut card"
	elseif not crop then status = "no crop" end
	if not usable(plain) then noPlain[#noPlain + 1] = p.id end
	if status == "ok" then ok = ok + 1 else issues[#issues + 1] = ("%s (%s): %s"):format(p.id, p.name, status) end
	rows[#rows + 1] = ("| %s | %s | %s | ctp_%s | %s | %s | %s | %s | %s | %s | %s |"):format(
		p.id, p.name, p.rarity or "common", p.id, digits(card), p.id, digits(plain), crop and "yes" or "NO", plaque, ring, seat) .. " " .. status .. " |"
end

local out = {}
out[#out + 1] = "# Patron art check"
out[#out + 1] = ""
out[#out + 1] = "Generated by `lua tools/patron_art_check.lua` from the registry and the art maps (code only, nothing loaded in Studio). Do not hand edit."
out[#out + 1] = ""
out[#out + 1] = ("Patrons: %d. Fully covered (cut card, crop, plain portrait where present): %d. Needing attention: %d."):format(#defs, ok, #issues)
out[#out + 1] = ""
out[#out + 1] = "Which picture each place draws: Counter, My Patrons and the seat circle go through `Client/PatronPlaque` (cut card `ctp_<id>`, else plain portrait `<id>`, else the emoji). The pick ring goes through `Engine/DraftPortrait` (cut card portrait window from `PatronCardCrop`, else plain portrait fitted whole, else the emoji)."
out[#out + 1] = ""
if #issues > 0 then
	out[#out + 1] = "## Needs attention"
	out[#out + 1] = ""
	for _, i in ipairs(issues) do out[#out + 1] = "- " .. i end
	out[#out + 1] = ""
end
if #noPlain > 0 then
	out[#out + 1] = "## No plain portrait (cut card only, no fallback if the card fails to load)"
	out[#out + 1] = ""
	out[#out + 1] = table.concat(noPlain, ", ")
	out[#out + 1] = ""
end
out[#out + 1] = "## All Patrons"
out[#out + 1] = ""
out[#out + 1] = "| id | name | rarity | card key | card id | plain key | plain id | crop | Counter and My Patrons | pick ring | seat circle | status |"
out[#out + 1] = "|---|---|---|---|---|---|---|---|---|---|---|---|"
for _, r in ipairs(rows) do out[#out + 1] = r end
out[#out + 1] = ""
local f = assert(io.open("claude/PATRON_ART_CHECK.md", "w"))
f:write(table.concat(out, "\n"))
f:close()
print(("wrote claude/PATRON_ART_CHECK.md: %d Patrons, %d ok, %d need attention"):format(#defs, ok, #issues))
for _, i in ipairs(issues) do print("  " .. i) end
