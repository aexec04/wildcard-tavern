#!/usr/bin/env python3
"""Writes claude/ART_STATUS.md: every art item the game can show, with done / missing marks.

An item is "done" when its generated map (src/Shared/Engine/*Art.lua) has a real rbxassetid://<digits>
(or, for Cosmetic Set backdrops, a non-placeholder backdropImage). "missing" items say whether a prompt
exists in tools/patron_art/prompts.json (generate it) or not (add a prompt first, or a whole new category).
Run `python3 tools/art_status.py` after each art batch. Read-only: it never calls any API.
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
ENGINE = ROOT / "src" / "Shared" / "Engine"
PROMPTS = json.loads((ROOT / "tools" / "patron_art" / "prompts.json").read_text(encoding="utf-8"))


def map_ids(lua_name):
    """key -> True when the generated map holds a real asset id."""
    path = ENGINE / lua_name
    out = {}
    if not path.exists():
        return out
    for key, val in re.findall(r'\["([^"]+)"\]\s*=\s*"rbxassetid://(\d+)"', path.read_text(encoding="utf-8")):
        out[key] = val != "0"
    return out


def registry_ids(lua_name, pattern=r'^\t\tid = "([a-z0-9_]+)"'):
    path = ENGINE / lua_name
    if not path.exists():
        return []
    return re.findall(pattern, path.read_text(encoding="utf-8"), re.M)


# (title, art map file, prompts key or None, registry file or None, note)
CATEGORIES = [
    ("Round backdrops (8 biomes)", "BiomeBackdropArt.lua", "biome_backdrop_subjects", None, "category biome_backdrops"),
    ("Region map tiles", "MapRegionArt.lua", "map_region_subjects", None, "category map_regions (8 biome tiles + road)"),
    ("Patron portraits", "PatronArt.lua", "subjects", "Patrons.lua", "category patrons (incl. 7 biome patrons)"),
    ("Recipe portraits", "RecipeArt.lua", "recipe_subjects", "Recipes.lua", "category recipes (incl. 7 biome recipes)"),
    ("Title portraits (incl. 16 biome titles, Winter Lanterns)", "TitleArt.lua", "title_subjects", None, "category titles"),
    ("Boss portraits", "BossRoundArt.lua", "boss_subjects", "BossRounds.lua", "category bosses"),
    ("House Pass art", "HousePassArt.lua", "housepass_subjects", "HousePasses.lua", "category housepasses"),
    ("Card back art (incl. Winter Lanterns, biome backs)", "CardBackArt.lua", "card_back_subjects", "CardBacks.lua", "category card_backs"),
    ("Shop pack icons", "PackArt.lua", "pack_subjects", None, "category packs"),
    ("Gameplay scenes", "SceneArt.lua", "scene_subjects", None, "category scenes"),
    ("Map nodes", "MapNodeArt.lua", "map_node_subjects", None, "category map_nodes"),
    ("Map decor", "MapDecorArt.lua", "map_decor_subjects", None, "category map_decor"),
    ("HUD pieces", "HudArt.lua", "hud_subjects", None, "category hud"),
    ("Menu icons", "MenuIconArt.lua", "menu_icon_subjects", None, "category menu_icons"),
    ("Backgrounds (incl. Counter and panel backgrounds)", "BackgroundArt.lua", "background_subjects", None, "category backgrounds"),
    ("Tutorial icons", "TutorialIconArt.lua", "tutorial_icon_subjects", None, "category tutorial_icons"),
    ("Rooms", "RoomArt.lua", "room_subjects", None, "category rooms"),
    ("FX textures", "FxArt.lua", "fx_subjects", None, "category fx (procedural)"),
]


def world_scenery():
    path = ENGINE / "WorldMap.lua"
    if not path.exists():
        return set()
    return set(re.findall(r'scenery = "([a-z_]+)"', path.read_text(encoding="utf-8")))


# Rule badges and biome badges (Engine/Badges.lua builds them from these ids)
BIOME_REGIONS = ["meadow", "river", "peaks", "desert", "swamp", "snow", "coast", "tavern"]
RULE_BADGES = ["wins_1", "wins_5", "wins_25", "night_3", "night_5", "night_8", "night_10", "minigame_1", "minigame_10",
               "collection_25", "collection_50", "collection_100", "streak_3", "streak_7", "streak_14", "season_winter_lanterns"]


def main():
    style = PROMPTS.get("style", "").lower()
    style_ok = "roblox" in style and "blocky" in style
    lines = ["# Art status", "",
             "Style check: " + ("OK (the avatar style prefix says Roblox and blocky)" if style_ok else "FAILED: the avatar style prefix lost the words Roblox / blocky (tools/patron_art/STYLE.md)"), "",
             "Generated by `python3 tools/art_status.py` (read-only). `[x]` = a real asset id is wired, `[ ]` = missing.",
             "A missing item is tagged `prompt` (a prompt exists: just generate it) or `NO PROMPT` (add one first).", ""]
    total_missing = 0
    for title, lua_name, prompt_key, registry, note in CATEGORIES:
        ids = map_ids(lua_name)
        prompts = set((PROMPTS.get(prompt_key) or {}).keys())
        # registry entries with no prompt and no id also count as missing (added content with no art plan)
        reg = set(registry_ids(registry)) if registry else set()
        if lua_name == "MapRegionArt.lua":
            reg = world_scenery()  # every biome the world map points at needs a tile
        keys = sorted(prompts | set(ids) | reg)
        if not keys:
            continue
        missing = [k for k in keys if not ids.get(k)]
        total_missing += len(missing)
        lines.append(f"## {title}  ({len(keys) - len(missing)}/{len(keys)} done) - {note}")
        for k in keys:
            if ids.get(k):
                lines.append(f"- [x] {k}")
            else:
                tag = "prompt" if k in prompts else "NO PROMPT"
                lines.append(f"- [ ] {k} ({tag})")
        lines.append("")

    # Cosmetic Set backdrops: backdropImage placeholders
    sets_src = (ENGINE / "CosmeticSets.lua").read_text(encoding="utf-8")
    backgrounds = map_ids("BackgroundArt.lua")
    lines.append("## Cosmetic Set backdrops (backdropImage)")
    set_missing = 0
    for block in re.finditer(r'\n\t\{\n\t\tid = "([a-z0-9_]+)",(.*?)\n\t\},', sets_src, re.S):
        sid, body = block.group(1), block.group(2)
        if sid == "classic_tavern":
            continue
        m = re.search(r'backdropImage = (.*?),\n', body)
        expr = m.group(1) if m else ""
        done = False
        art_key = re.search(r'BackgroundArt\.(\w+)', expr)
        if art_key:
            done = bool(backgrounds.get(art_key.group(1)))
        elif re.search(r'rbxassetid://[1-9]', expr):
            done = True
        lines.append(f"- [{'x' if done else ' '}] {sid}" + ("" if done else " (NO PROMPT: needs a backdrop category/prompts; the set's backdropStyle covers the look meanwhile)"))
        if not done:
            set_missing += 1
    total_missing += set_missing
    lines.append("")

    # Badges: no art category yet
    badge_ids = ["biome_" + r for r in BIOME_REGIONS] + ["master_" + r for r in BIOME_REGIONS] + RULE_BADGES
    lines.append(f"## Badge icons ({len(badge_ids)}; emoji today)")
    lines.append("No art category yet: add a `badges` category (prompts + CATEGORY_OPTS + BadgeArt.lua + ContentArt) before generating.")
    for b in badge_ids:
        lines.append(f"- [ ] {b} (NO PROMPT)")
    total_missing += len(badge_ids)
    lines.append("")
    lines.append(f"**Total missing: {total_missing}**")
    out = ROOT / "claude" / "ART_STATUS.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)} ({total_missing} missing)")


if __name__ == "__main__":
    sys.exit(main())
