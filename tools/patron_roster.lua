-- Writes claude/PATRON-ROSTER.md: every Patron with rarity, price and ability text, plus flags.
-- Run: lua tools/patron_roster.lua
local loader = dofile("tools/sim/EngineLoader.lua")
local engine = loader.load("src/Shared")
local P, CB = engine.Patrons, engine.CollectionBook
local list = P.Definitions or P.List or P

-- Rarity is read the same way the shop and Collection read it.
local function rarityOf(d) return CB.rarityOf({ id = d.id, tab = "patrons", def = d }) end

local bandPrice = { common = { 4, 6 }, uncommon = { 5, 7 }, rare = { 8, 8 }, epic = { 7, 8 }, legendary = { 8, 8 }, mythical = { 8, 8 } }

local out = {
	"# Patron roster", "",
	"Generated by `lua tools/patron_roster.lua`. Rarity comes from CollectionBook.rarityOf (own field, then override, then price rule: 8 rare, 7 uncommon, else common).",
	"", "| Patron | Rarity | Price | Ability text |", "| --- | --- | --- | --- |",
}
local flags = {}
for _, d in ipairs(list) do
	local text = d.description or ""
	local r = rarityOf(d)
	out[#out + 1] = string.format("| %s | %s | %d | %s |", d.name or d.id, r, d.price or 0, text)
	if #text > 60 then flags[#flags + 1] = string.format("- Text over 60 chars (%d): %s: %s", #text, d.id, text) end
	local band = bandPrice[r]
	if band and ((d.price or 0) < band[1] or (d.price or 0) > band[2]) then
		flags[#flags + 1] = string.format("- Price %d out of line with %s: %s", d.price or 0, r, d.id)
	end
end
out[#out + 1] = ""
out[#out + 1] = "## Flags from the script"
for _, f in ipairs(flags) do out[#out + 1] = f end
if #flags == 0 then out[#out + 1] = "- none" end

out[#out + 1] = ""
out[#out + 1] = "## Flags left for a design call (not changed)"
for _, line in ipairs({
	"- Near duplicates: Double Down (+10 Mult, exactly Two Pair, price 6) beats Twin Spoons (+6 Mult, price 5); Straight Shooter (+18 Mult, contains Straight) beats Long Road (+12 Mult, price 6); Threes Company (+18) beats Triple Treat (+12) at the same price.",
	"- Price vs rarity: the seven biome Patrons are Uncommon at price 5, cheaper than Common ones at 6. House Favorite is Legendary, and House Special, Full House Crowd, Veterans Table and House Tab are Epic, all at the same price 8 as Rare ones.",
	"- Copiers (The Understudy, The Apprentice, Second Opinion) are distinct by direction, kept.",
	"- Fixing these changes balance and shop odds, so it needs the owner's call.",
}) do out[#out + 1] = line end

local f = assert(io.open("claude/PATRON-ROSTER.md", "w"))
f:write(table.concat(out, "\n"), "\n")
f:close()
print(#list .. " Patrons, " .. #flags .. " flags")
for _, x in ipairs(flags) do print(x) end
