"""Fit test for set_panels art (slice-friendly panel borders).

Writes src/Shared/Engine/SetPanelFit.lua: per set, the share of opaque pixels in the 9-slice centre and edge bands
(SliceCenter 92,61 to 1444,963 on a 1536x1024 canvas) and whether the art passes. Passing means the centre is mostly
clear (<= CENTRE_MAX) and every edge band is mostly filled (>= EDGE_MIN), so slicing at the band thickness shows a frame
and not a hollow or patchy one. Run after new set_panels art: python3 tools/patron_art/measure_panel_fit.py
"""
import importlib.util, json, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
CENTRE_MAX, EDGE_MIN = 0.12, 0.35

spec = importlib.util.spec_from_file_location("measure_skin_art", ROOT / "tools/patron_art/measure_skin_art.py")
m = importlib.util.module_from_spec(spec)
spec.loader.exec_module(m)

ids = json.loads((ROOT / "art-wip/set_panels/image-ids.json").read_text())
rows = []
for sid in sorted(ids):
    w, h, a = m.read_alpha(str(ROOT / f"art-wip/set_panels/{sid}.png"))

    def frac(x0, y0, x1, y1):
        n = o = 0
        for y in range(y0, y1, 4):
            for x in range(x0, x1, 4):
                n += 1
                o += 1 if a[y][x] > 40 else 0
        return o / n

    cx0, cy0, cx1, cy1 = int(w * 92 / 1536), int(h * 61 / 1024), int(w * 1444 / 1536), int(h * 963 / 1024)
    centre = frac(cx0 + 40, cy0 + 40, cx1 - 40, cy1 - 40)
    edge = min(frac(0, cy0, cx0, cy1), frac(cx1, cy0, w, cy1), frac(cx0, 0, cx1, cy0), frac(cx0, cy1, cx1, h))
    rows.append((sid, round(centre, 2), round(edge, 2), centre <= CENTRE_MAX and edge >= EDGE_MIN))

lines = [
    "--[[",
    "\tShared/Engine/SetPanelFit.lua",
    "\tGENERATED by tools/patron_art/measure_panel_fit.py -- do not hand-edit.",
    "\tPer set: centre (opaque share of the slice centre), edge (lowest opaque share of the four edge bands), pass.",
    "\tCosmeticSets.skinOf only uses a set's SetPanelArt id as panelFrame9 when pass is true.",
    "]]",
    "",
    "return {",
]
for sid, c, e, ok in rows:
    lines.append(f'\t["{sid}"] = {{ centre = {c}, edge = {e}, pass = {str(ok).lower()} }},')
lines.append("}")
(ROOT / "src/Shared/Engine/SetPanelFit.lua").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("passing:", [r[0] for r in rows if r[3]])
print("failing:", [r[0] for r in rows if not r[3]])
