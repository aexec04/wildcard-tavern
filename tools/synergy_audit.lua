-- Writes claude/synergy-audit.md: which Patron pairs fire a synergy hint (they share a non-"flat" tag, the rule in
-- Engine/Gameplay2Synergy.links) and flags any Patron with no partner. Run: lua tools/synergy_audit.lua
local loader = dofile("tools/sim/EngineLoader.lua")
local engine = loader.load("src/Shared")
local list = engine.Patrons.Definitions

local byTag, partners, pairCount = {}, {}, 0
for _, d in ipairs(list) do
	partners[d.id] = {}
	for _, t in ipairs(d.tags or {}) do
		if t ~= "flat" then
			byTag[t] = byTag[t] or {}
			table.insert(byTag[t], d.id)
		end
	end
end
local seenPair = {}
for _, ids in pairs(byTag) do
	for i = 1, #ids do
		for j = i + 1, #ids do
			local a, b = ids[i], ids[j]
			local key = a < b and (a .. "|" .. b) or (b .. "|" .. a)
			if not seenPair[key] then
				seenPair[key] = true
				pairCount = pairCount + 1
				partners[a][b] = true
				partners[b][a] = true
			end
		end
	end
end
local out = { "# Patron synergy audit", "",
	"Generated by `lua tools/synergy_audit.lua`. A pair fires a hint when the two Patrons share a tag other than flat (Engine/Gameplay2Synergy.links, Engine/Synergy).", "",
	string.format("%d Patrons, %d hint pairs.", #list, pairCount), "", "## Patrons per tag", "" }
local tags = {}
for t in pairs(byTag) do tags[#tags + 1] = t end
table.sort(tags)
for _, t in ipairs(tags) do out[#out + 1] = string.format("- %s: %d Patrons", t, #byTag[t]) end
out[#out + 1] = ""
out[#out + 1] = "## Patrons with the fewest partners"
out[#out + 1] = ""
local rows = {}
for _, d in ipairs(list) do
	local n = 0
	for _ in pairs(partners[d.id]) do n = n + 1 end
	rows[#rows + 1] = { id = d.id, n = n, tags = table.concat(d.tags or {}, ",") }
end
table.sort(rows, function(a, b) if a.n ~= b.n then return a.n < b.n end return a.id < b.id end)
for i = 1, math.min(10, #rows) do out[#out + 1] = string.format("- %s: %d partners (tags: %s)", rows[i].id, rows[i].n, rows[i].tags) end
out[#out + 1] = ""
local none = {}
for _, r in ipairs(rows) do if r.n == 0 then none[#none + 1] = r.id end end
out[#out + 1] = "## Patrons with no hint"
out[#out + 1] = ""
out[#out + 1] = #none == 0 and "None. Every Patron has at least one partner." or table.concat(none, ", ")
out[#out + 1] = ""
local f = assert(io.open("claude/synergy-audit.md", "w"))
f:write(table.concat(out, "\n"))
f:close()
print(table.concat(out, "\n"))
