"""Writes claude/MODERATION-CHECK.md: every uploaded image id by category with its prompt line and a tick box.
Run: python3 -I tools/gen_moderation_check.py   (reads src/Shared/Engine/*Art.lua and tools/patron_art/prompts.json, no network, no spend)"""
import glob
import json
import os
import re

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
prompts = json.load(open(os.path.join(root, "tools/patron_art/prompts.json")))
subject_maps = {k: v for k, v in prompts.items() if isinstance(v, dict) and k.endswith("subjects")}
pair = re.compile(r'\["([^"]+)"\]\s*=\s*"rbxassetid://(\d+)"')


def prompt_for(key, cat):
    # prefer the subjects map that belongs to this category, then any map holding the key
    low = cat.lower()
    ordered = sorted(subject_maps, key=lambda m: 0 if low.startswith(m.split("_")[0][:4]) else 1)
    for m in ordered:
        v = subject_maps[m].get(key)
        if isinstance(v, str):
            return v
    return None


out = ["# Asset moderation checklist", "",
       "Generated by `python3 -I tools/gen_moderation_check.py`. One line per uploaded image id, grouped by art map.",
       "Open each id in Creator Hub (Inventory, Decals) and tick the box once it is approved and still looks kid safe.", ""]
total = 0
for f in sorted(glob.glob(os.path.join(root, "src/Shared/Engine/*Art.lua"))):
    cat = os.path.basename(f)[:-len("Art.lua")]
    pairs = pair.findall(open(f).read())
    if not pairs:
        continue
    out += ["## " + cat + " (" + str(len(pairs)) + ")", ""]
    for key, rid in pairs:
        p = prompt_for(key, cat)
        line = (p if p else "(no prompt line in prompts.json)").replace("\n", " ")
        if len(line) > 160:
            line = line[:157] + "..."
        out.append("- [ ] `%s` `%s` %s" % (key, rid, line))
        total += 1
    out.append("")
out.insert(3, "Total ids: %d" % total)
open(os.path.join(root, "claude/MODERATION-CHECK.md"), "w").write("\n".join(out) + "\n")
print(total)
