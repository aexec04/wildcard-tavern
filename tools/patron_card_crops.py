"""Measure the portrait window of every Concept T Patron card and write src/Shared/Engine/PatronCardCrop.lua.

The cut cards sit at a slightly different place and scale in each 1024x1536 picture, so a fixed crop is wrong. For each card:
find the card body (pixels that differ from the corner backdrop colour; the gem on top is skipped by taking the first row whose
run is at least 60 percent of the widest run), then the portrait window is the body inset 8 percent each side, 7 percent from the
top and 17 percent from the bottom (the baked name plate). Usage: python3 -I tools/patron_card_crops.py [--sheet]
Output is generated, never hand edited. --sheet writes art-wip/concept_t_patrons/_crop_sheet_<n>.png to check by eye."""
import glob
import os
import sys

import numpy as np
from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "art-wip", "concept_t_patrons")
OUT = os.path.join(ROOT, "src", "Shared", "Engine", "PatronCardCrop.lua")
INSET_X, INSET_TOP, INSET_BOTTOM = 0.10, 0.09, 0.20


def measure(path):
    im = Image.open(path).convert("RGBA")
    a = np.asarray(im).astype(int)
    h, w = a.shape[:2]
    corner = np.median(np.concatenate([a[:6, :6, :3].reshape(-1, 3), a[:6, -6:, :3].reshape(-1, 3)]), axis=0)
    diff = np.abs(a[:, :, :3] - corner).sum(axis=2) > 45
    diff &= a[:, :, 3] > 40
    runs = []
    for y in range(h):
        xs = np.nonzero(diff[y])[0]
        runs.append((int(xs[0]), int(xs[-1])) if len(xs) > 20 else None)
    widths = [(r[1] - r[0]) if r else 0 for r in runs]
    wmax = max(widths)
    rows = [y for y in range(h) if widths[y] >= 0.6 * wmax]
    top, bottom = rows[0], rows[-1]
    left, right = runs[(top + bottom) // 2]
    cw, ch = right - left, bottom - top
    return {
        "x": int(left + cw * INSET_X),
        "y": int(top + ch * INSET_TOP),
        "w": int(cw * (1 - 2 * INSET_X)),
        "h": int(ch * (1 - INSET_TOP - INSET_BOTTOM)),
    }


def main():
    files = sorted(glob.glob(os.path.join(SRC, "ctp_*.png")))
    res = {}
    for f in files:
        res[os.path.basename(f)[4:-4]] = measure(f)
    lines = [
        "-- GENERATED by tools/patron_card_crops.py, never hand edited.",
        "-- Portrait window (pixels) of each Concept T Patron cut card (1024 x 1536): inside the baked frame, above the baked name plate.",
        "return {",
    ]
    for k in sorted(res):
        r = res[k]
        lines.append("\t%s = { x = %d, y = %d, w = %d, h = %d }," % (k, r["x"], r["y"], r["w"], r["h"]))
    lines.append("}")
    with open(OUT, "w", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote", len(res), "crops")
    if "--sheet" in sys.argv:
        keys = sorted(res)
        for n in range(0, len(keys), 21):
            sheet = Image.new("RGB", (7 * 220, 3 * 330), "white")
            for i, k in enumerate(keys[n:n + 21]):
                im = Image.open(os.path.join(SRC, "ctp_%s.png" % k)).convert("RGB")
                r = res[k]
                d = ImageDraw.Draw(im)
                d.rectangle([r["x"], r["y"], r["x"] + r["w"], r["y"] + r["h"]], outline=(255, 0, 0), width=8)
                sheet.paste(im.resize((220, 330)), ((i % 7) * 220, (i // 7) * 330))
            sheet.save(os.path.join(SRC, "_crop_sheet_%d.png" % (n // 21)))


main()
