"""Measure art-wip/ledger_ui/ledger_book_open.png and write src/Shared/Engine/LedgerBookGeometry.lua (generated).

Finds, per page: the paper quad, the ruled lines (start/end point fractions and angle) and the paper colour.
Also writes art-wip/_checks/ledger_geometry.png (quads and lines drawn over the art) to look at.
Run: python3 tools/measure_ledger_book.py
"""
import math
import os
import numpy as np
from PIL import Image, ImageDraw

SRC = "art-wip/ledger_ui/ledger_book_open.png"
OUT = "src/Shared/Engine/LedgerBookGeometry.lua"
DBG = "art-wip/_checks/ledger_geometry.png"

im = Image.open(SRC).convert("RGB")
W, H = im.size
a = np.asarray(im).astype(float)
g = a.sum(2)

# page search windows (x ranges inside the cream paper, well away from the leather)
PAGES = {"left": (215, 690), "right": (870, 1330)}


def cream(px):
    r, gg, b = px
    return r > 200 and gg > 160 and 90 < b < 215 and r - b > 25


def edge_scan(y, x0, x1):
    xs = [x for x in range(x0, x1) if cream(a[y, x])]
    return (xs[0], xs[-1]) if xs else None


def fit_line(ys_at_x):
    xs = np.array(sorted(ys_at_x))
    ys = np.array([ys_at_x[x] for x in xs], float)
    m, c = np.polyfit(xs, ys, 1)
    return m, c


result = {}
dbg = im.copy()
d = ImageDraw.Draw(dbg)
for name, (x0, x1) in PAGES.items():
    # ruled line rows: local dark peaks of the column-mean profile
    col = g[:, x0 + 40:x1 - 40].mean(1)
    sm = np.convolve(col, np.ones(15) / 15, "same")
    dd = sm - col
    rows = [y for y in range(200, 800) if dd[y] > 12 and dd[y] == dd[max(0, y - 6):y + 7].max()]
    lines = []
    for y0 in rows:
        # follow the stroke: for each x column find the darkest y within +-6 of the running estimate
        pts = {}
        yy = y0
        for x in range(x0 + 8, x1 - 8, 4):
            win = g[max(0, int(yy) - 5):int(yy) + 6, x]
            yy = max(0, int(yy) - 5) + int(np.argmin(win))
            loc = g[max(0, int(yy) - 12):int(yy) + 13, x].mean()
            if loc - g[int(yy), x] > 4:
                pts[x] = yy
        if len(pts) < 15:
            continue
        xs = sorted(pts)
        # keep the long run of stroke points (drop stray ends)
        xl, xr = xs[2], xs[-3]
        sub = {x: pts[x] for x in xs if xl <= x <= xr}
        m, c = fit_line(sub)
        lines.append({"x0": xl, "y0": m * xl + c, "x1": xr, "y1": m * xr + c, "ang": math.degrees(math.atan(m))})
    # quad from the paper edges at the first and last line (top and bottom of the paper)
    top_y = 150
    while top_y < 400 and not (edge_scan(top_y, x0, x1) and edge_scan(top_y, x0, x1)[1] - edge_scan(top_y, x0, x1)[0] > (x1 - x0) * 0.5):
        top_y += 1
    bot_y = 840
    while bot_y > 600 and not (edge_scan(bot_y, x0, x1) and edge_scan(bot_y, x0, x1)[1] - edge_scan(bot_y, x0, x1)[0] > (x1 - x0) * 0.5):
        bot_y -= 1
    tl, tr = edge_scan(top_y + 8, x0, x1)
    bl, br = edge_scan(bot_y - 24, x0, x1)
    quad = [(tl, top_y + 8), (tr, top_y + 8), (br, bot_y - 24), (bl, bot_y - 24)]
    cx0, cx1 = (x0 + x1) // 2 - 30, (x0 + x1) // 2 + 30
    cy0, cy1 = (top_y + bot_y) // 2 - 30, (top_y + bot_y) // 2 + 30
    rgb = a[cy0:cy1, cx0:cx1].reshape(-1, 3).mean(0)
    # page colour between lines (avoid the stroke): median of the patch
    rgb = np.median(a[cy0:cy1, cx0:cx1].reshape(-1, 3), axis=0)
    result[name] = {"quad": quad, "lines": lines, "paper": "%02X%02X%02X" % tuple(int(v) for v in rgb)}
    d.polygon(quad, outline=(0, 255, 255))
    for ln in lines:
        d.line([(ln["x0"], ln["y0"]), (ln["x1"], ln["y1"])], fill=(255, 0, 255), width=2)

# gutter: dark vertical strip between the pages
mid = g[300:700, 690:870].mean(0)
gx = 690 + int(np.argmin(mid))
d.line([(gx, 140), (gx, 880)], fill=(0, 255, 0), width=1)
os.makedirs(os.path.dirname(DBG), exist_ok=True)
dbg.save(DBG)


def fx(v):
    return "%.4f" % (v / W)


def fy(v):
    return "%.4f" % (v / H)


out = ["-- GENERATED by tools/measure_ledger_book.py from art-wip/ledger_ui/ledger_book_open.png. Do not hand-edit.",
       "-- Fractions of the book image (x of width, y of height). Lines: start and end point plus angle in degrees.",
       "return {",
       "\tgutterX = %s," % fx(gx),
       "\taspect = %.4f," % (W / H)]
for name in ("left", "right"):
    p = result[name]
    out.append("\t%s = {" % name)
    out.append("\t\tpaper = \"%s\"," % p["paper"])
    out.append("\t\tquad = { " + ", ".join("{ %s, %s }" % (fx(x), fy(y)) for x, y in p["quad"]) + " },")
    out.append("\t\tlines = {")
    for ln in p["lines"]:
        out.append("\t\t\t{ x0 = %s, y0 = %s, x1 = %s, y1 = %s, angle = %.2f }," % (fx(ln["x0"]), fy(ln["y0"]), fx(ln["x1"]), fy(ln["y1"]), ln["ang"]))
    out.append("\t\t},")
    out.append("\t},")
out.append("}")
open(OUT, "w").write("\n".join(out) + "\n")
for name in ("left", "right"):
    print(name, result[name]["paper"], result[name]["quad"], len(result[name]["lines"]), "lines",
          [round(l["ang"], 2) for l in result[name]["lines"]])
print("gutter", gx)
